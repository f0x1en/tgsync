"""Write spec/vectors.json: fixed examples of every format in PROTOCOL.md.

Run after changing the protocol:  .venv/bin/python scripts/make_vectors.py
tests/test_vectors.py checks that the Python code still agrees with the file; the
TypeScript plugin tests read the same file. The age keys in it are throwaway test keys.
"""

from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from tgsync import invites, oplog, paths, vaultkeys
from tgsync.crypto import KeyRing, _subkey, fingerprint, mac
from tgsync.identity import generate, member_id
from tgsync.tree import Tree

OUT = Path(__file__).resolve().parent.parent / "spec" / "vectors.json"
K1 = bytes(range(32))
K2 = bytes(range(100, 132))
H = bytes.hex


def seal_fixed(key: bytes, epoch: int, purpose: bytes, ctx: bytes, plain: bytes, nonce: bytes) -> bytes:
    """KeyRing.seal with a chosen nonce, so the output is reproducible."""
    header = struct.pack(">4sI", b"TGS1", epoch)
    return header + nonce + AESGCM(_subkey(key, purpose, ctx)).encrypt(nonce, plain, header + purpose + b"\0" + ctx)


def main() -> None:
    v: dict = {"note": "Generated by scripts/make_vectors.py. Bytes are hex unless named *_b64. See PROTOCOL.md."}

    v["subkey"] = [{"key": H(K1), "purpose": p, "ctx": c, "subkey": H(_subkey(K1, p.encode(), c.encode()))}
                   for p, c in [("record", ""), ("chunk", "0011223344556677:0:3"), ("roster", "a1b2c3d4e5f60718")]]

    v["seal"] = []
    for epoch, key, purpose, ctx, plain in [(1, K1, "record", "", b"hello"),
                                            (2, K2, "chunk", "0011223344556677:1:2", bytes(range(256))),
                                            (1, K1, "roster", "a1b2c3d4e5f60718", "ünïcode ✓".encode())]:
        nonce = bytes([epoch] * 12)
        v["seal"].append({"epoch": epoch, "key": H(key), "purpose": purpose, "ctx": ctx, "nonce": H(nonce),
                          "plaintext": H(plain), "blob": H(seal_fixed(key, epoch, purpose.encode(), ctx.encode(), plain, nonce))})
    good = bytes.fromhex(v["seal"][0]["blob"])
    v["open_must_fail"] = [
        {"why": "tag tampered", "blob": H(good[:-1] + bytes([good[-1] ^ 1])), "purpose": "record", "ctx": ""},
        {"why": "wrong purpose", "blob": H(good), "purpose": "chunk", "ctx": ""},
        {"why": "unknown epoch", "blob": H(good[:4] + struct.pack(">I", 9) + good[8:]), "purpose": "record", "ctx": ""},
        {"why": "bad magic", "blob": H(b"XXXX" + good[4:]), "purpose": "record", "ctx": ""},
        {"why": "too short", "blob": H(good[:20]), "purpose": "record", "ctx": ""},
    ]
    v["open_ring"] = {"1": H(K1), "2": H(K2)}

    v["mac"] = [{"key": H(K1), "parts": ["descriptor", "a1b2c3d4e5f60718", "1"],
                 "mac": H(mac(K1, b"descriptor", b"a1b2c3d4e5f60718", b"1"))}]
    v["fingerprint"] = [{"key": H(k), "fingerprint": fingerprint(k)} for k in (K1, K2)]

    alice, bob = generate(), generate()
    v["identities"] = {n: {"secret": i.secret, "recipient": i.recipient, "id": member_id(i.recipient),
                           "short_code": invites.short_code(i.recipient)} for n, i in (("alice", alice), ("bob", bob))}

    # descriptors: create (alice), add bob, remove bob (rotates to epoch 2)
    vid = "a1b2c3d4e5f60718"
    ring = KeyRing({1: K1})
    am, bm = vaultkeys.Member(alice.recipient, "alice"), vaultkeys.Member(bob.recipient, "bob")
    d1 = vaultkeys.build(ring, vid, [am])
    d2, members = vaultkeys.add_member(ring, vid, [am], bm)
    rot = KeyRing(ring.export())
    d3, _ = vaultkeys.remove_member(rot, vid, members, "bob")
    forged = json.loads(d2)
    forged["created"] += 1  # body changed after signing
    v["descriptors"] = {
        "vault_id": vid,
        "sequence": [d.decode() for d in (d1, d2, d3)],
        "expect_alice": [{"epoch": 1, "members": ["alice"]}, {"epoch": 1, "members": ["alice", "bob"]},
                         {"epoch": 2, "members": ["alice"]}],
        "expect_bob": ["excluded", {"epoch": 1, "members": ["alice", "bob"]}, "excluded"],
        "epoch2_key": H(rot.key(2)),
        "forged_after_d1": json.dumps(forged, sort_keys=True, separators=(",", ":")),
    }

    # a record with two inline files and a delete, plus a chunk
    payload = b"# hi\n" + b"note two"
    entries = [
        {"op": "put", "path": "notes/hello.md", "base": None, "mtime": 1762850000.25, "sha": oplog_sha(b"# hi\n"),
         "size": 5, "blob": {"file_id": "00000000000000aa", "chunks": None, "inline": [0, 5]}},
        {"op": "put", "path": "ünï/two.md", "base": None, "mtime": 1762850001.0, "sha": oplog_sha(b"note two"),
         "size": 8, "blob": {"file_id": "00000000000000bb", "chunks": None, "inline": [5, 8]}},
        {"op": "delete", "path": "old.md", "base": "0" * 64},
        {"op": "mkdir", "path": "empty/folder"},
    ]
    header = json.dumps({"v": 1, "author": member_id(alice.recipient), "seq": 1, "ts": 1762850002.5, "entries": entries},
                        separators=(",", ":")).encode()
    plain = struct.pack(">I", len(header)) + header + payload
    v["record"] = {"key": H(K1), "epoch": 1, "blob": H(seal_fixed(K1, 1, b"record", b"", plain, bytes(12))),
                   "author": member_id(alice.recipient), "seq": 1, "ts": 1762850002.5, "entries": entries,
                   "payload": H(payload)}
    rec = oplog.decode_record(KeyRing({1: K1}), bytes.fromhex(v["record"]["blob"]))
    assert rec.entries == entries and rec.payload == payload
    v["chunk"] = {"key": H(K1), "file_id": "00000000000000cc", "index": 1, "count": 3, "data": H(b"chunk-bytes"),
                  "blob": H(seal_fixed(K1, 1, b"chunk", b"00000000000000cc:1:3", b"chunk-bytes", bytes([7] * 12)))}

    inv = invites.Invite("https://t.me/+AbCdEf123", vid, fingerprint(K1), (12345, "0123456789abcdef0123456789abcdef"))
    v["invite"] = {"code": invites.encode_invite(inv), "link": inv.link, "vault_id": vid, "fingerprint": inv.fingerprint,
                   "api": [12345, "0123456789abcdef0123456789abcdef"]}
    v["join_request"] = {"body": invites.encode_request(vid, bob, "bob").decode(), "vault": vid,
                         "recipient": bob.recipient, "name": "bob"}

    v["paths"] = []
    for p in ["a.md", "notes/x.md", "e\u0301.md", "/abs", "C:/x", "a/../b", "a//b", "./a", "con.txt", "x/LPT1",
              "bad?.md", "a\\b", "trail. ", "dot./x", ".tgsync/state.db", ".git/x", "f.tgsync-tmp",
              "a" * 241, "", ".obsidian/app.json", "x\x01y"]:
        try:
            v["paths"].append({"in": p, "ok": True, "out": paths.normalize(p)})
        except Exception:
            v["paths"].append({"in": p, "ok": False})
    v["conflict_name"] = [{"path": p, "author": "abcdef0123456789", "ts": 1762850000.0,
                           "out": paths.conflict_name(p, "abcdef0123456789", 1762850000.0)}
                          for p in ["n.md", "dir/sub/n.tar.gz", "noext", ".gitignore", "d/.hidden"]]

    v["replay"] = replay_vector()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(v, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {OUT}", file=sys.stderr)


def oplog_sha(b: bytes) -> str:
    import hashlib
    return hashlib.sha256(b).hexdigest()


def replay_vector() -> dict:
    """A log of records (already opened) and the results/tree every client must reach."""
    A, B = "aaaaaaaaaaaaaaaa", "bbbbbbbbbbbbbbbb"
    blob = {"file_id": "00000000000000aa", "chunks": None, "inline": [0, 1]}

    def put(path, sha, base=None, extra=None):
        e = {"op": "put", "path": path, "sha": sha, "size": 1, "mtime": 1.0, "base": base, "blob": dict(blob)}
        e.update(extra or {})
        return e

    s1, s2, s3 = "1" * 64, "2" * 64, "3" * 64
    log = [
        {"msg_id": 10, "author": A, "ts": 1762850000.0, "entries": [put("n.md", s1), put("Case.md", s1), {"op": "mkdir", "path": "dir"}]},
        {"msg_id": 11, "author": B, "ts": 1762850060.0, "entries": [put("n.md", s2, s1)]},  # fast-forward
        {"msg_id": 12, "author": A, "ts": 1762850120.0, "entries": [put("n.md", s3, s1)]},  # stale base -> conflict
        {"msg_id": 13, "author": B, "ts": 1762850180.0, "entries": [put("case.md", s2)]},   # case clash -> conflict
        {"msg_id": 14, "author": A, "ts": 1762850240.0, "entries": [{"op": "delete", "path": "n.md", "base": s1}]},  # stale: ignored
        {"msg_id": 15, "author": A, "ts": 1762850300.0, "entries": [{"op": "delete", "path": "Case.md", "base": s1}]},
        {"msg_id": 16, "author": B, "ts": 1762850360.0, "entries": [put("moved.md", s2, None, {"blob": {**blob, "payload_msg": 11}})]},
        {"msg_id": 17, "author": B, "ts": 1762850420.0, "entries": [{"op": "mkdir", "path": "n.md"}, {"op": "rmdir", "path": "dir"},
                                                                     {"op": "put", "path": "../evil", "sha": s1}, {"op": "bogus", "path": "x"}]},
        {"msg_id": 18, "author": A, "ts": 1762850150.0, "entries": [put("n.md", s3, s1)]},  # same minute as msg 12: name taken -> "aaaaa2"
        {"msg_id": 19, "author": B, "ts": 1762850500.0, "entries": [put("Straße.md", s1), put("STRASSE.md", s2), put("ΣΊΣΥΦΟΣ.md", s1), put("σίσυφος.md", s2)]},  # lower(), not casefold
    ]
    t = Tree()
    results = []
    for m in log:
        for e in m["entries"]:
            r = t.apply_entry(json.loads(json.dumps(e)), m["author"], m["ts"], m["msg_id"])
            results.append(list(r) if r else None)
    return {"log": log, "results": results,
            "tree": {p: {"sha": n.sha, "author": n.author, "msg_id": n.msg_id, "payload_msg": n.blob.get("payload_msg")}
                     for p, n in sorted(t.nodes.items())}}


if __name__ == "__main__":
    main()
